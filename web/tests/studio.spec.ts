import { test, expect } from '@playwright/test'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..')
test('local creation, configuration, crop, model alignment and skinning', async ({ page, request, baseURL }) => {
  const consoleErrors: string[] = []
  page.on('pageerror', error => consoleErrors.push(error.message))
  const external: string[] = []
  page.on('request', req => { if (/^https?:/.test(req.url()) && !req.url().startsWith(baseURL!)) external.push(req.url()) })
  await page.goto('/')
  await expect(page.getByText('让想象，')).toBeVisible()
  await page.screenshot({path:path.join(root,'data','welcome.png'),fullPage:true})
  await page.getByRole('button',{name:'创建第一个角色'}).click()
  await page.getByRole('textbox',{name:'为这个角色取个名字'}).fill('荒野旅人 · 界面测试')
  await page.getByRole('button',{name:'确定',exact:true}).click()
  await expect(page.getByRole('heading',{name:'荒野旅人 · 界面测试'})).toBeVisible()
  await page.getByLabel('角色设计提示词').fill('一位年轻的奇幻游侠，红色披风，米白色衬衣，棕色皮革腰带。完整角色，保留左肩的金色徽章。')
  await page.getByRole('button',{name:'保存设计',exact:true}).click()
  await expect(page.getByText('设计已保存')).toBeVisible()
  await page.getByLabel('关闭提示').click()
  await page.screenshot({path:path.join(root,'data','studio.png'),fullPage:true})
  await page.getByRole('button',{name:/02.*三视图/}).click()
  const sheetChooser=page.waitForEvent('filechooser')
  await page.getByRole('button',{name:'导入三视图'}).click()
  await (await sheetChooser).setFiles(path.join(root,'data','smoke-test','sheet.png'))
  await expect(page.getByAltText('待拆分角色三视图')).toBeVisible()
  await page.getByRole('checkbox',{name:/我已确认三个视图/}).check()
  await page.getByRole('button',{name:'确认并拆分为三张图'}).click()
  await expect(page.getByRole('heading',{name:'检查完毕，进入三维。'})).toBeVisible()
  await expect(page.getByAltText('正面 / FRONT')).toBeVisible()
  await page.screenshot({path:path.join(root,'data','crop.png'),fullPage:true})
  await page.getByLabel('关闭提示').click()
  await page.getByRole('button',{name:'模型与工具设置'}).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await expect(page.getByLabel('骨架模板 .blend')).toHaveValue(String.raw`D:\独立游戏\Client\Role1\骨骼和身体.blend`)
  await page.screenshot({path:path.join(root,'data','settings.png'),fullPage:true})
  // The smoke-test output preserves the template sources and bones. Use this
  // fixture instead of requiring the user's original template to stay in place.
  await page.getByLabel('骨架模板 .blend').fill(path.join(root,'data','smoke-test','bind','character.blend'))
  await page.getByRole('button',{name:'保存设置',exact:true}).click()
  await page.getByRole('button',{name:/04.*骨架与蒙皮/}).click()
  await page.getByRole('button',{name:'检测模板',exact:true}).click()
  await expect(page.getByText('41',{exact:true})).toBeVisible({timeout:20000})
  await expect(page.getByRole('button',{name:'检测模板',exact:true})).toBeEnabled()
  const items = await request.get('/api/projects')
  const project=(await items.json())[0]
  const prompt=project.prompt
  expect(prompt).toContain('游侠')
  // No remote generation is invoked. The source for this test model is a template mesh copy.
  await page.getByRole('button',{name:/03.*3D 模型/}).click()
  const fileChooser=page.waitForEvent('filechooser')
  await page.getByRole('button',{name:'导入 GLB'}).click()
  await (await fileChooser).setFiles(path.join(root,'data','smoke-test','fixture.glb'))
  await expect(page.getByText('拖动旋转 · 滚轮缩放',{exact:true})).toBeVisible({timeout:15000})
  await page.screenshot({path:path.join(root,'data','model.png'),fullPage:true})
  await page.getByRole('button',{name:'适配我的骨架'}).click()
  await page.getByRole('button',{name:'生成对齐预览'}).click()
  await expect(page.getByText('拖动旋转 · 滚轮缩放 · 绿色线框为模板人体')).toBeVisible({timeout:30000})
  await expect(page.getByRole('button',{name:'确认对齐，开始蒙皮'})).toBeEnabled({timeout:10000})
  await page.screenshot({path:path.join(root,'data','alignment.png'),fullPage:true})
  page.once('dialog',d=>d.accept())
  await page.getByRole('button',{name:'确认对齐，开始蒙皮'}).click()
  await expect(page.getByRole('heading',{name:'检查每一个动作细节。'})).toBeVisible({timeout:45000})
  await expect(page.getByText('未绑定 0',{exact:true})).toHaveCount(2)
  await page.getByRole('button',{name:'屈肘测试'}).click()
  await expect(page.getByRole('link',{name:'BLEND',exact:true})).toBeVisible()
  await page.screenshot({path:path.join(root,'data','skinning.png'),fullPage:true})
  expect(consoleErrors).toEqual([])
  expect(external).toEqual([])
  await page.setViewportSize({width:390,height:844})
  await page.screenshot({path:path.join(root,'data','mobile.png'),fullPage:true})
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth)
  expect(overflow).toBe(false)
})
